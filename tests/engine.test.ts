// Player & ball engine acceptance tests (real Rapier physics, headless).
// Run: npx tsx tests/engine.test.ts      (add --report to rewrite docs/ACCEPTANCE_REPORT.md)
import { writeFileSync } from 'node:fs';
import { runChecks } from '../packages/game-engine/development/PhysicsTests.ts';

const results = await runChecks();
let failed = 0;
for (const r of results) {
  if (!r.pass) failed++;
  console.log(`${r.pass ? 'PASS' : 'FAIL'}  ${String(r.id).padStart(2)}. ${r.name} — ${r.detail}`);
}
console.log(`\n${results.length - failed}/${results.length} engine checks passed`);

if (process.argv.includes('--report')) {
  const rows = results.map((r) => `| ${r.id} | ${r.name} | ${r.pass ? '✅ Pass' : '❌ Fail'} | ${r.detail.replace(/\|/g, '/')} |`).join('\n');
  const md = `# Player & Ball acceptance report\n\nGenerated by \`npx tsx tests/engine.test.ts --report\` on ${new Date().toISOString().slice(0, 10)}.\nEvery row runs the real engine (Rapier, fixed 60 Hz step) headlessly and measures the behaviour.\nItem 42 (no TypeScript errors) is checked by \`npm run typecheck\`.\n\n| # | Check | Result | Measured |\n|---|---|---|---|\n${rows}\n`;
  writeFileSync(new URL('../docs/ACCEPTANCE_REPORT.md', import.meta.url), md);
  console.log('wrote docs/ACCEPTANCE_REPORT.md');
}
process.exit(failed ? 1 : 0);
