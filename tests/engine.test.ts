// Player & ball engine acceptance tests (real Rapier physics, headless).
//   npx tsx tests/engine.test.ts            run everything
//   npx tsx tests/engine.test.ts --report   also rewrite docs/ACCEPTANCE_REPORT.md
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { runChecks } from '../packages/game-engine/development/PhysicsTests.ts';
import { GAMEPLAY_TESTS, GameplayRunner } from '../packages/game-engine/development/GameplayTests.ts';
import { Simulation } from '../packages/game-engine/physics/Simulation.ts';

interface Row { group: string; name: string; pass: boolean; detail: string }
const rows: Row[] = [];

// 1. Physics / movement / ball checks
for (const r of await runChecks()) rows.push({ group: `Engine ${r.id}`, name: r.name, pass: r.pass, detail: r.detail });

// 2. Gameplay tests A–D (scripted controller input, same as the Lab)
for (const t of GAMEPLAY_TESTS) {
  const sim = await Simulation.create();
  const p = sim.addPlayer({ id: 'reference', name: 'Reference Player', number: 10, start: { x: 0, z: 0 }, seed: 7 });
  const res = new GameplayRunner(sim, p, t).runAll();
  for (const c of res) rows.push({ group: `Test ${t.id} · ${t.name}`, name: c.name, pass: c.pass, detail: c.detail });
  rows.push({ group: `Test ${t.id} · ${t.name}`, name: 'No conflicting ball impulses in one step', pass: sim.interaction.conflicts === 0, detail: `${sim.interaction.conflicts} dropped` });
}

// 3. Static check: only the central interaction system writes ball velocity.
function files(dir: string): string[] {
  return readdirSync(dir).flatMap((f) => { const p = join(dir, f); return statSync(p).isDirectory() ? files(p) : /\.tsx?$/.test(f) ? [p] : []; });
}
const root = fileURLToPath(new URL('../packages/game-engine/', import.meta.url));
const writers = files(root).filter((f) => !f.includes('/development/') && !f.endsWith('BallController.ts') && !f.endsWith('BallPhysics.ts') && !f.endsWith('BallCollision.ts'))
  .filter((f) => /\bball\.kick\(|\.physics\.kick\(|setLinvel\([^)]*\)/.test(readFileSync(f, 'utf8')) && !f.endsWith('PlayerBallInteraction.ts') && !f.endsWith('PlayerPhysics.ts'));
rows.push({ group: 'Architecture', name: 'One authoritative writer of ball velocity', pass: writers.length === 0, detail: writers.length ? `also written in: ${writers.join(', ')}` : 'only PlayerBallInteraction (queued, one impulse per step)' });

let failed = 0;
for (const r of rows) {
  if (!r.pass) failed++;
  console.log(`${r.pass ? 'PASS' : 'FAIL'}  [${r.group}] ${r.name} — ${r.detail}`);
}
console.log(`\n${rows.length - failed}/${rows.length} engine checks passed`);

if (process.argv.includes('--report')) {
  const esc = (s: string) => s.replace(/\|/g, '/');
  const table = rows.map((r) => `| ${r.group} | ${esc(r.name)} | ${r.pass ? '✅ Pass' : '❌ Fail'} | ${esc(r.detail)} |`).join('\n');
  const md = `# Player & Ball acceptance report\n\nGenerated by \`npx tsx tests/engine.test.ts --report\` on ${new Date().toISOString().slice(0, 10)}.\nEvery row runs the real engine (Rapier, fixed 60 Hz step) headlessly. Gameplay tests A–D feed scripted controller input (exactly what the keyboard produces) to the reference player and check the typed event log; the Player & Ball Lab runs the same scripts live (Gameplay tests tab).\nTypeScript compilation is checked by \`npm run typecheck\`.\n\n| Group | Check | Result | Measured |\n|---|---|---|---|\n${table}\n`;
  writeFileSync(new URL('../docs/ACCEPTANCE_REPORT.md', import.meta.url), md);
  console.log('wrote docs/ACCEPTANCE_REPORT.md');
}
process.exit(failed ? 1 : 0);
